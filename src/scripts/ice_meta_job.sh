#!/bin/bash
# One ICE-table meta learner (M6): train on the train ICs (best epoch on val) -> test record + checkpoint, then frozen
# inference on the other splits from that checkpoint. D1 v2, x_only obs, teacher = strong-Wolfe L-BFGS (lr 1).
# Usage: bash src/scripts/ice_meta_job.sh <cell c1|c2|c3|c4> <model f1|emulator> <constraint strong|weak> <seed>
#                                         ["<splits>" (default "test test_ood")] ["<extra overrides>"]
# Env: SMOKE=1 -> 10 train ICs, 20 val ICs, 20 eval cases, 2 epochs (dev check; results under ice_smoke).
#      OSSE=1  -> no training: the learner trained on D1 v2 (tmp/meta/ice_meta_<model>) is applied FROZEN to the OSSE
#                 observations generated by F1 (data prefix l63v2osse, src/make_osse_obs.py); results ice_osse_meta_<model>
cd "$(dirname "$0")/../.."
export OMP_NUM_THREADS=1 MKL_NUM_THREADS=1
P=/Odyssey/private/j25lee/miniforge3/envs/oceanai/bin/python
C=$1; M=$2; CON=$3; S=$4; SPLITS=${5:-"test test_ood"}; EXTRA=$6
case $C in
  # cell 1 = supervised learned optimizer (delta_exact): history input (L-BFGS memory m 10), output relative to the
  # L-BFGS two-loop direction, two-step target, online training, log loss / selection, backtrack safeguard at inference
  c1) X="variant=delta_exact delta_exact.hist_m=10 delta_exact.base=lbfgs delta_exact.first_step=teacher \
delta_exact.hidden=32 delta_exact.batch_size=64 delta_exact.horizon=2 delta_exact.train_loss=logmean \
delta_exact.select=logmean delta_exact.train_mode=online delta_exact.online_cases=100 delta_exact.epochs=30 \
delta_exact.safeguard=backtrack delta_exact.seed=$S delta_exact.pairs_cache=tmp/meta/ice_${M}/pairs_${CON}";;
  # cell 2 = unsupervised learned optimizer (delta, output free): same learner as cell 1 (history input, L-BFGS base,
  # Wolfe first step, backtrack safeguard at inference) trained on its own trajectory by the first-order decrease of
  # J along its move (l_perf) + small align to the Wolfe teacher step (training only) + L2; best epoch on val
  c2) X="variant=delta delta.output=free net.hidden=32 delta.hist_m=10 delta.base=lbfgs delta.first_step=teacher \
delta.safeguard=backtrack delta.w_perf_delta=2.5 delta.w_align=0.1 delta.meta_lr=1e-3 delta.n_epochs=10 \
delta.batch=100 delta.episode_iters=20 delta.select_epoch=true delta.select_k=10 delta.select_n_val=200 \
delta.train_seed=$S delta.pairs_cache=tmp/meta/ice_${M}/pairs_${CON}";;
  *) echo "unknown cell $C"; exit 1;;
esac
G=ice_meta_$M; NTR=null; NVP=200; NC=null
if [ -n "$SMOKE" ]; then
  G=ice_smoke_$M; NTR=10; NVP=20; NC=20
  X="${X/delta_exact.epochs=30/delta_exact.epochs=2}"
  X="${X/delta.n_epochs=10/delta.n_epochs=1}"
  X="${X/delta.select_n_val=200/delta.select_n_val=20}"
  X="${X/tmp\/meta\/ice_${M}/tmp/meta/ice_smoke_${M}}"
fi
PREFIX=l63v2; CKDIR=tmp/meta/$G
if [ -n "$OSSE" ]; then PREFIX=l63v2osse; G=ice_osse_meta_$M; fi
EMU=""; [ "$M" = emulator ] && EMU="emulator=rho275"
NAME=${C}_${CON}_s$S
COMMON="dataset=v2 data_prefix=$PREFIX model=$M $EMU constraint=$CON pattern=x_only problem=bice method=lbfgs_wolfe lr=1 \
max_iter=150 tol=1e-6 train.n_train=$NTR train.n_val_pairs_ic=$NVP n_cases=$NC result_group=$G tag=_$NAME"
mkdir -p tmp/logs/ice tmp/meta/ice_$M tmp/meta/ice_smoke_$M
FIRST=1; [ -n "$OSSE" ] && FIRST=0                                   # OSSE: every split from the checkpoint
for SP in $SPLITS; do
  if [ $FIRST = 1 ]; then                                          # train + first split
    $P src/run_meta_b.py $COMMON $X split=$SP hydra.run.dir=tmp/hydra/ice/${G}_${NAME}_$SP $EXTRA \
      > tmp/logs/ice/${G}_${NAME}_$SP.log 2>&1 || exit 1
    FIRST=0
  else                                                               # frozen inference from the checkpoint
    CK=$(ls $CKDIR/*_${CON}_x_only_lbfgs_wolfe_lr1_${NAME}.pt | head -1)
    $P src/run_meta_b.py $COMMON $X split=$SP checkpoint=$CK hydra.run.dir=tmp/hydra/ice/${G}_${NAME}_$SP $EXTRA \
      > tmp/logs/ice/${G}_${NAME}_$SP.log 2>&1 || exit 1
  fi
done
