"""
Command lists of the classical rows of the ICE table (M6) for src/scripts/sb_parallel.sh (one run per line).

    python src/scripts/ice_lists.py finals   -> src/scripts/lists/ice_finals.txt
        GD / Adam / Adagrad / Wolfe L-BFGS on test and test_ood (200 cases each) with the per-iterate G1 hook,
        models truth (E1) / f1 / emulator (F2) x strong / weak, x_only obs.
No lr sweep (pilot, 2026-11-19): Wolfe L-BFGS is the reference (lr 1, line search). GD / Adagrad reuse the D1 v2
full-pattern selection of m5 (tmp/results/v2_<model>_sweep/selected_lr.json); Adam (new) uses lr 0.1 everywhere.
First-order rows are therefore reported as "lr not re-tuned for x_only".
    python src/scripts/ice_lists.py osse     -> src/scripts/lists/ice_osse.txt
        OSSE group (pilot 2026-11-19, replaces E1): observations generated by F1 (src/make_osse_obs.py, prefix
        l63v2osse), 4D-Var with F1 = perfect-model twin; same 4 references and lr as the F1 rows.
Results: tmp/results/ice_<model>/ and tmp/results/ice_osse_f1/ ; logs: tmp/logs/ice/
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MODELS = ("truth", "f1", "emulator")
CONSTRAINTS = ("strong", "weak")
# lr per (model, constraint): m5 D1 v2 selection for gd / adagrad (full pattern), Adam fixed 0.1, L-BFGS line search
LR = {("truth", "strong"): {"gd": 1e-3, "adagrad": 1.0}, ("truth", "weak"): {"gd": 3e-4, "adagrad": 0.1},
      ("f1", "strong"): {"gd": 1e-3, "adagrad": 0.3}, ("f1", "weak"): {"gd": 1e-3, "adagrad": 0.1},
      ("emulator", "strong"): {"gd": 1e-3, "adagrad": 0.3}, ("emulator", "weak"): {"gd": 3e-4, "adagrad": 0.1}}
ADAM_LR = 0.1
COMMON = "pattern=x_only problem=bice max_iter=1000 tol=1e-6"


def line(model, constraint, method, lr, split, group, extra=""):
    name = f"{group}_{constraint}_{method}_lr{lr:g}_{split}"
    return (f"python src/run_4dvar_v2.py model={model} constraint={constraint} method={method} lr={lr:g} "
            f"split={split} {COMMON} result_group={group} hydra.run.dir=tmp/hydra/ice/{name} {extra}".rstrip()
            + f" > tmp/logs/ice/{name}.log 2>&1")


def finals():
    out = []
    for model in MODELS:
        for constraint in CONSTRAINTS:
            lr = LR[(model, constraint)]
            runs = [("gd", lr["gd"]), ("adam", ADAM_LR), ("adagrad", lr["adagrad"]), ("lbfgs_wolfe", 1.0)]
            for method, lr_m in runs:
                for split in ("test", "test_ood"):
                    out.append(line(model, constraint, method, lr_m, split, f"ice_{model}", "g1_iter=true"))
    return out


def osse(models=("f1", "emulator")):
    """OSSE (observations generated by F1): the 4 references for each estimation model (F1 = no model error, F2 =
    emulator of F1) -> tmp/results/ice_osse_<model>/."""
    out = []
    for model in models:
        for constraint in CONSTRAINTS:
            lr = LR[(model, constraint)]
            runs = [("gd", lr["gd"]), ("adam", ADAM_LR), ("adagrad", lr["adagrad"]), ("lbfgs_wolfe", 1.0)]
            for method, lr_m in runs:
                for split in ("test", "test_ood"):
                    out.append(line(model, constraint, method, lr_m, split, f"ice_osse_{model}",
                                    "g1_iter=true data_prefix=l63v2osse"))
    return out


if __name__ == "__main__":
    stage = sys.argv[1]                               # osse: optional model names after the stage
    lines = finals() if stage == "finals" else osse(tuple(sys.argv[2:]) or ("f1", "emulator"))
    path = ROOT / f"src/scripts/lists/ice_{stage}.txt"
    path.write_text(f"# ICE table, classical rows: {stage} ({len(lines)} runs), generated by src/scripts/ice_lists.py\n"
                    + "\n".join(lines) + "\n")
    print(f"{len(lines)} commands -> {path}")
