"""
ICE tables (M6, final design 2026-11-20): 4D-Var initial-condition estimation, x_only obs, strong / weak, estimation
models F1 (L63 rho 27.5, our knowledge model) and F2 (emulator rho275). The SAME experiment twice, only the
observations differ:
    Table 1  OSSE  observations generated by F1 (src/make_osse_obs.py); the meta learners are TRAINED on OSSE data.
    Table 2  OSE   observations of the real system E1 (L63 rho 28); the OSSE-trained learners are applied FROZEN.
                   Supplementary rows: learners trained on the OSE observations themselves ("OSE-trained").
Rows per (constraint, model): first guess, GD / Adam / Adagrad / L-BFGS (strong Wolfe), meta cells 1-4 (3 seeds).
Columns (mean ± std over cases; every split has 200 cases):
    rmse_x0          analysis initial-condition error vs the truth of the table (F1 trajectory in OSSE, E1 in OSE)
    fc1_true         forecast RMSE at 1 TU (lead 100) from the analysis, run with the table's TRUE model (IC quality;
                     in the OSE a diagnostic only: the real model is unknown in practice)
    fc1_model        same, run with the estimation model (operational forecast)
    traj_model       trajectory error of the estimation model from the analysis vs the truth, mean over lead 0 .. 1 TU
                     (OSE: the real-world question "is our model's trajectory closer to the truth despite model error")
    grads_to_1pct    gradient evaluations (forward + adjoint, line-search trials included) until J <= 1.01 J*
                     (cell 4, adjoint-free: forward runs converted to gradient equivalents, grad_cost_ratio.json),
                     J* = best final J over the classical methods of the same table / model / constraint / case
    reached          fraction of cases reaching 1.01 J*
    grads_total      gradient evaluations until the stopping rule
    wall_s           optimizer wall-clock for the 200-case batch (one thread; G1 hook time excluded)
    g1_fg / g1_an    G1 = cos(consumed gradient, true-model gradient) at the first guess / at the last iterate
    train_s          meta: training wall-clock (teacher run + fit) per seed, mean ± std over the 3 seeds
    seed_spread      meta: std over seeds of the per-seed mean rmse_x0
Meta rows pool the 3 seeds (mean ± std over cases x seeds).

Usage (project root):  python src/report_ice.py   -> tmp/results/ice/ice_table_{osse,ose}_{test,test_ood}.{md,csv}
"""

import json
from pathlib import Path

import numpy as np
import pandas as pd
import xarray as xr

ROOT = Path(__file__).resolve().parent.parent
MODEL_LABEL = {"f1": "F1 (L63 ρ 27.5)", "emulator": "F2 (emulator ρ 27.5)"}
# table -> (title, {model: (classical results dir, [(meta results dir, row suffix), ...])})
TABLES = {
    "osse": ("Table 1 — OSSE: observations generated by F1; meta learners trained on OSSE",
             {m: (f"ice_osse_{m}", [(f"ice_osse_meta_{m}", "")]) for m in ("f1", "emulator")}),
    "ose": ("Table 2 — OSE: observations of the real system E1; OSSE-trained meta learners applied frozen",
            {m: (f"ice_{m}", [(f"ice_ose_meta_{m}", ""), (f"ice_meta_{m}", " [suppl.: OSE-trained]")])
             for m in ("f1", "emulator")}),
}
METHODS = {"gd": "GD", "adam": "Adam", "adagrad": "Adagrad", "lbfgs_wolfe": "L-BFGS (strong Wolfe)"}
# meta cells (src/scripts/ice_meta_job.sh): records tmp/results/ice_meta_<model>/*_<cell>_<constraint>_s<seed>_<split>.nc
CELLS = {"c1": "cell 1 supervised learned optimizer", "c2": "cell 2 unsupervised learned optimizer",
         "c3": "cell 3 learned optimization (unroll)", "c4": "cell 4 adjoint-free learned gradient"}
LEAD_1TU = 100
COMPACT = ["constraint", "model", "method", "trained_on", "rmse_x0", "traj_model", "fc1_model", "fc1_true", "grads_to_1pct",
           "reached"]


def traj(rmse_fc):
    """Per-case trajectory error of OUR model from the analysis vs the truth, averaged over lead 0 .. 1 TU (end of
    window -> 1 TU ahead): the real-world question (b) 'does 4D-Var bring our model's trajectory closer to the truth'."""
    return rmse_fc.sel(lead=slice(0, LEAD_1TU)).mean("lead").values


def load(cdir, constraint, split):
    """{method: Dataset} of the classical finals in results dir cdir for one (constraint, split)."""
    out = {}
    for p in sorted((ROOT / "tmp/results" / cdir).glob(f"bice_{constraint}_x_only_*_{split}.nc")):
        ds = xr.load_dataset(p)
        out[json.loads(ds.attrs["config"])["method"]] = ds
    return out


def ms(a, fmt="{:.3f}"):
    """'mean ± std' over finite values."""
    a = np.asarray(a, float)
    a = a[np.isfinite(a)]
    return "—" if a.size == 0 else (fmt + " ± " + fmt).format(a.mean(), a.std())


def last_finite(a):
    """[ic, k] -> value at the last finite k per case."""
    idx = np.where(np.isfinite(a), np.arange(a.shape[1])[None], -1).max(1)
    return np.where(idx >= 0, a[np.arange(len(a)), np.maximum(idx, 0)], np.nan)


GRAD_COST = json.loads((ROOT / "tmp/results/grad_cost_ratio.json").read_text())   # gradient = ratio x forward run


def cost_cum(ds, model, constraint):
    """[ic, k] model-run cost to reach iterate k in GRADIENT EQUIVALENTS: grad_cum (forward + adjoint runs) or, for the
    adjoint-free cell 4, fwd_cum (forward runs) / (gradient / forward wall-clock ratio of the same model)."""
    if "fwd_cum" in ds:
        key = ("emulator" if model == "emulator" else "f1") + f"/{constraint}"
        return ds.fwd_cum.values / GRAD_COST[key]["ratio"]
    return ds.grad_cum.values


def grads_to_target(ds, j_star, model="f1", constraint="strong"):
    hit = ds.J_iter.values <= 1.01 * j_star[:, None]
    k = np.where(hit.any(1), hit.argmax(1), -1)
    gc = cost_cum(ds, model, constraint)
    return np.where(k >= 0, gc[np.arange(len(k)), np.maximum(k, 0)], np.nan)


def rows(table, model, constraint, split):
    cdir, meta_dirs = TABLES[table][1][model]
    runs = load(cdir, constraint, split)
    if not runs:
        return []
    j_star = np.nanmin(np.stack([d.J_iter.values[:, -1] for d in runs.values()]), 0)
    any_ds = next(iter(runs.values()))
    base = {"constraint": constraint, "model": MODEL_LABEL[model]}
    out = [{**base, "method": "first guess", "lr": "", "rmse_x0": ms(any_ds.rmse_x0_b.values),
            "fc1_true": "", "fc1_model": ms(any_ds.rmse_fc_b.sel(lead=LEAD_1TU).values),
            "traj_model": ms(traj(any_ds.rmse_fc_b))}]
    for m, label in METHODS.items():
        if m not in runs:
            continue
        ds = runs[m]
        cfg = json.loads(ds.attrs["config"])
        g2t = grads_to_target(ds, j_star)
        out.append({**base, "method": label, "lr": "line search" if m == "lbfgs_wolfe" else f"{cfg['lr']:g}",
                    "rmse_x0": ms(ds.rmse_x0.values),
                    "fc1_true": ms(ds.rmse_fc_m1.sel(lead=LEAD_1TU).values),
                    "fc1_model": ms(ds.rmse_fc.sel(lead=LEAD_1TU).values), "traj_model": ms(traj(ds.rmse_fc)),
                    "grads_to_1pct": ms(g2t, "{:.1f}"), "reached": f"{np.isfinite(g2t).mean():.2f}",
                    "grads_total": ms(ds.grad_cum.values[:, -1], "{:.1f}"),
                    "wall_s": f"{float(ds.attrs['wall_s']):.1f}",
                    "g1_fg": ms(ds.g1_grad.values[:, 0]), "g1_an": ms(last_finite(ds.g1_grad.values)),
                    "diverged": int(ds.diverged.sum())})
    for (mdir, suffix), (cell, label) in [(md, c) for md in meta_dirs for c in CELLS.items()]:
        recs = sorted((ROOT / "tmp/results" / mdir).glob(f"*_{cell}_{constraint}_s*_{split}.nc"))
        if not recs:
            continue
        dss = [xr.load_dataset(p) for p in recs]
        trained_on = {provenance(d, mdir) for d in dss}                 # raises on a record of the wrong origin
        cat = lambda f: np.concatenate([f(d) for d in dss])                     # noqa: E731  pooled over seeds
        g2t = cat(lambda d: grads_to_target(d, j_star, model, constraint))
        train = [json.loads(d.attrs["train_info"]).get("train_wall_s", np.nan) for d in dss]
        train = [t for t in train if t is not None and np.isfinite(t)]
        out.append({**base, "method": f"{label} ({len(dss)} seeds){suffix}", "lr": "learned",
                    "trained_on": "/".join(sorted(trained_on)),
                    "rmse_x0": ms(cat(lambda d: d.rmse_x0.values)),
                    "fc1_true": ms(cat(lambda d: d.rmse_fc_m1.sel(lead=LEAD_1TU).values)),
                    "fc1_model": ms(cat(lambda d: d.rmse_fc.sel(lead=LEAD_1TU).values)),
                    "traj_model": ms(cat(lambda d: traj(d.rmse_fc))),
                    "grads_to_1pct": ms(g2t, "{:.1f}"), "reached": f"{np.isfinite(g2t).mean():.2f}",
                    "grads_total": ms(cat(lambda d: cost_cum(d, model, constraint)[:, -1]), "{:.1f}"),
                    "wall_s": ms([float(d.attrs["wall_s"]) for d in dss], "{:.1f}"),
                    "train_s": ms(train, "{:.0f}") if train else "",
                    "seed_spread": f"{np.std([np.nanmean(d.rmse_x0.values) for d in dss]):.3f}",
                    "diverged": int(sum(int(d.diverged.sum()) for d in dss))})
    return out


def provenance(ds, mdir: str) -> str:
    """Where the learner of a meta record was TRAINED (pilot 2026-11-20: the main-table meta must be OSSE-trained).
    Returns the training data set ('OSSE' or 'OSE') and raises if the record does not match its table:
        ice_osse_meta_*  trained on l63v2osse (this run) or loaded from tmp/meta/ice_osse_meta_*, evaluated on l63v2osse
        ice_ose_meta_*   frozen learner loaded from tmp/meta/ice_osse_meta_*, evaluated on l63v2 (real observations)
        ice_meta_*       supplementary: trained on l63v2 (real observations) or loaded from tmp/meta/ice_meta_*"""
    cfg, info = json.loads(ds.attrs["config"]), json.loads(ds.attrs["train_info"])
    src = info.get("loaded_from", "")
    prefix = cfg.get("data_prefix", "l63v2")
    if mdir.startswith("ice_osse_meta_"):
        ok = prefix == "l63v2osse" and (not src or "/ice_osse_meta_" in src)
        trained = "OSSE"
    elif mdir.startswith("ice_ose_meta_"):
        ok = prefix == "l63v2" and "/ice_osse_meta_" in src
        trained = "OSSE"
    else:
        ok = prefix == "l63v2" and (not src or "/ice_meta_" in src)
        trained = "OSE"
    if not ok:
        raise ValueError(f"provenance mismatch in {mdir}: data_prefix {prefix}, learner {src or 'trained here'}")
    return trained


def to_markdown(df: pd.DataFrame) -> str:
    """Plain markdown table (the env has no `tabulate`)."""
    head = "| " + " | ".join(df.columns) + " |"
    sep = "|" + "|".join("---" for _ in df.columns) + "|"
    body = ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([head, sep] + body)


def main():
    out_dir = ROOT / "tmp/results/ice"
    out_dir.mkdir(parents=True, exist_ok=True)
    for table, (title, models) in TABLES.items():
        for split in ("test", "test_ood"):
            tab = [r for c in ("strong", "weak") for m in models for r in rows(table, m, c, split)]
            df = pd.DataFrame(tab).fillna("")
            if table == "ose" and not df.empty:          # real-world check (a): every row, compact columns (pilot)
                df = df[[c for c in COMPACT if c in df.columns]]
            df.to_csv(out_dir / f"ice_table_{table}_{split}.csv", index=False)
            md = f"# {title} — {split} (200 cases, x_only obs, mean ± std over cases)\n\n" + to_markdown(df)
            (out_dir / f"ice_table_{table}_{split}.md").write_text(md + "\n")
            print(md, "\n")


if __name__ == "__main__":
    main()
