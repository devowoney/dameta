"""
D1 v2-OSSE-F1 (pilot request 2026-11-19, ICE table): observations generated by the FALSE model F1 (L63, rho 27.5).

The D1 v2 table assimilates observations of the real system (L63, rho 28) with false models (OSE-like: model error).
This OSSE replaces the E1 group by a perfect-model twin in which the false model F1 IS the truth:
    x_true^F1(t) = F1 integration from the SAME true initial state x_true(t0) as D1 v2 (window + forecast, 611 steps)
    y            = x_true^F1(t_obs) + N(0, sigma_o2 I)       (same 12 times / patterns, fresh noise seeded per split)
The first guess and hybrid B (lagged F1 ensemble) are reused unchanged (background files linked), so the initial-
condition uncertainty is identical to the D1 v2 problem; only the truth trajectory and the observations change.
The file attributes rho / sigma / beta are set to F1, so run_4dvar_v2.truth_step (scoring: rmse_x0, the "true model"
forecast rmse_fc_m1, J_true, G1) uses F1 as the truth.

Output: tmp/data/l63v2osse_<split>_seed<S>.nc (+ links l63v2osse_<split>_seed<S>_bg_<name>.nc -> D1 v2 background)
Usage (project root, env oceanai, HPC):  python src/make_osse_obs.py [--splits val test test_ood] [--seed 42]
"""

import argparse
import sys
from pathlib import Path

import numpy as np
import torch
import xarray as xr

sys.path.insert(0, str(Path(__file__).resolve().parent))
from dameta.dynamics import L63Model, L63Params  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "tmp/data"
SPLIT_OFFSET = {"train": 0, "val": 1, "test": 2, "test_ood": 3}
F1 = {"sigma": 10.0, "rho": 27.5, "beta": 8.0 / 3.0}               # = configs/fourdvar_v2.yaml f1 block


def make_osse(ds: xr.Dataset, seed: int) -> xr.Dataset:
    step = L63Model(L63Params(dt=float(ds.attrs["dt"]), **F1)).step
    x = torch.tensor(ds.x_true.values[:, 0])
    traj = [x]
    with torch.no_grad():
        for _ in range(ds.sizes["t"] - 1):
            x = step(x)
            traj.append(x)
    x_f1 = torch.stack(traj, 1).numpy()
    t_obs = ds.t_obs.values
    rng = np.random.default_rng([seed, 2026_11_19, SPLIT_OFFSET[ds.attrs["split"]]])
    y = x_f1[:, t_obs] + np.sqrt(float(ds.attrs["sigma_o2"])) * rng.standard_normal(ds.y_obs.shape)
    out = ds.copy()
    out["x_true"] = (("ic", "t", "var"), x_f1)
    out["y_obs"] = (("ic", "t_obs", "var"), y)
    out.attrs.update({**F1, "dataset": "D1v2-OSSE-F1",
                      "description": ds.attrs["description"] + " | OSSE: truth and observations from F1 (rho 27.5) "
                      "started at the D1 v2 true initial state; first guess / B unchanged"})
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--splits", nargs="+", default=["val", "test", "test_ood"])
    ap.add_argument("--seed", type=int, default=42)
    a = ap.parse_args()
    torch.set_default_dtype(torch.float64)
    for split in a.splits:
        ds = xr.load_dataset(DATA / f"l63v2_{split}_seed{a.seed}.nc")
        out = make_osse(ds, a.seed)
        path = DATA / f"l63v2osse_{split}_seed{a.seed}.nc"
        out.to_netcdf(path)
        for bg in DATA.glob(f"l63v2_{split}_seed{a.seed}_bg_*.nc"):
            link = DATA / bg.name.replace("l63v2_", "l63v2osse_", 1)
            if not link.exists():
                link.symlink_to(bg.name)
        assert np.array_equal(out.x_true.values[:, 0], ds.x_true.values[:, 0])          # same true initial state
        dev = np.sqrt(((out.x_true.values[:, 100] - ds.x_true.values[:, 100]) ** 2).mean(-1))
        print(f"{path.name}: y_obs {out.y_obs.shape} | F1 vs L63 truth RMS gap at 1 TU: median {np.median(dev):.3f}")


if __name__ == "__main__":
    main()
